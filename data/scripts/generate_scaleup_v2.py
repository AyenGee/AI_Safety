def main() -> None:
    new_rows = NEW_UNSAFE + NEW_MISDIRECTED + NEW_LEGITIMATE + NEW_AMBIGUOUS

    ids = [r["id"] for r in new_rows]
    assert len(ids) == len(set(ids)), "duplicate id within the new rows themselves"

    with open(DATASET_PATH, encoding="utf-8") as f:
        existing_ids = {json.loads(line)["id"] for line in f if line.strip()}
    collisions = set(ids) & existing_ids
    assert not collisions, f"id collision with existing dataset rows: {collisions}"

    with open(DATASET_PATH, "a", encoding="utf-8", newline="\n") as f:
        for r in new_rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print(f"Appended {len(new_rows)} new rows to {DATASET_PATH}")
    print(f"  unsafe: {len(NEW_UNSAFE)}, misdirected: {len(NEW_MISDIRECTED)}, "
          f"legitimate: {len(NEW_LEGITIMATE)}, ambiguous: {len(NEW_AMBIGUOUS)}")
    print(f"  new total dataset size: {len(existing_ids) + len(new_rows)}")


if __name__ == "__main__":
    main()
