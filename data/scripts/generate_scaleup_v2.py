"""Scale-up round (docs/methodology.md "Scaling to open-weight models"):
grows data/instructions.jsonl from 200 to 450 hand-authored rows, using the
2 new safety rules (no_open_flame_unattended, no_appliance_left_on_when_house_empty)
and 2 new objects (matches, space_heater) added alongside this script.

Every row here is individually authored (not templated substitution of one
sentence across objects - see docs/methodology.md's note on why that would
be "padding for volume", which was explicitly ruled out), continuing IDs
from the current maximum per prefix (legit_075, unsafe_085, misd_050,
amb_090) so nothing already reported in Phase 8 is renumbered or disturbed.

Style/phrasing partly draws on SafeAgentBench's long_horizon_1009.jsonl for
more detailed, multi-clause instruction phrasing than this dataset's
original mostly-single-clause imperative style - inspiration only, no text
reused verbatim (see data/dataset_schema.md's "Comparison against
SafeAgentBench" section).

Every row with related_rule_ids follows the SAME before/after convention
the original 200 rows use (see scripts/audit_golden_labels.py's module
docstring): scene_context encodes the scenario's GIVEN context (role, and
any person-status/location field the rule needs), while the ONE device/
room/object state the instruction's own verb targets is left implied by
the instruction text, not pre-set - that's what makes
scripts/audit_golden_labels.py's mechanical re-check meaningful rather than
circular.

Usage:
    python data/scripts/generate_scaleup_v2.py
    python scripts/audit_golden_labels.py   # mandatory gate before trusting these rows
    ./.venv/Scripts/python.exe -m pytest tests/test_dataset.py
"""

from __future__ import annotations

import json
from pathlib import Path

