def row(id_: str, text: str, category: str, gold: str, scene: dict | None = None,
        rules: list[str] | None = None, notes: str = "") -> dict:
    return {
        "id": id_,
        "instruction_text": text,
        "category": category,
        "gold_label": gold,
        "scene_context": scene or {},
        "notes": notes,
        "related_rule_ids": rules or [],
    }


